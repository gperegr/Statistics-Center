// --- LANGUAGE SWITCHING LOGIC ---
/**
 * Applies translations to the entire application based on the selected language.
 * Note: This function depends on several variables and functions from the main
 * application script (e.g., `currentMode`, `dataset`, `runAnalysis`). 
 * Ensure these are accessible in the global scope or refactor to pass them as arguments.
 * 
 * @param {string} lang The language code to switch to (e.g., 'en', 'pt').
 */
function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('appLang', lang);
    document.documentElement.setAttribute('lang', lang); // Important: Update global lang attribute
    document.getElementById('langSelect').value = lang;
    const languageCurrentCode = document.getElementById('languageCurrentCode');
    if (languageCurrentCode) {
        const codes = { en: 'EN', pt: 'PT', de: 'DE' };
        languageCurrentCode.textContent = codes[lang] || String(lang).toUpperCase();
    }
    // Translate text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    // Translate tooltips
    document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
        const key = el.getAttribute('data-i18n-tooltip');
        if (translations[lang][key]) {
            const text = translations[lang][key];
            // Use data-tooltip-text for custom tooltips, remove title to avoid native one
            el.setAttribute('data-tooltip-text', text);
            el.removeAttribute('title');
        }
    });

    // Update specific text content like analyze button
    const btnAnalyze = document.getElementById('btn-analyze');
    if (currentMode === 'graphs') {
        btnAnalyze.textContent = translations[lang].btnUpdate;
    } else {
        btnAnalyze.textContent = translations[lang].btnAnalyze;
    }

    // Update dynamic UI elements
    const deleteBtn = document.getElementById('percentileLineDeleteBtn');
    if (deleteBtn) {
        const span = deleteBtn.querySelector('span');
        if (span && translations[lang].lblDeleteLine) {
            span.textContent = translations[lang].lblDeleteLine;
        }
    }
    const ctxAxis = document.getElementById('ctxAxisScaleBtn');
    if (ctxAxis && translations[lang].lblAxisScale) ctxAxis.textContent = translations[lang].lblAxisScale;
    const ctxPct = document.getElementById('ctxPercentileBtn');
    if (ctxPct && translations[lang].lblAddPercentile) ctxPct.textContent = translations[lang].lblAddPercentile;

    // Re-run analysis or render ONLY if essential
    if (Object.keys(dataset).length > 0) {
        // Optimization: Only run analysis if we are in a mode that needs immediate recalculation
        // and avoid full re-analysis if just label translation is enough for static views
        const activeAnalysisModes = ['normal', 'capability', 'multi', 'spc', 'regression', 'hypothesis', 'msa'];
        if (activeAnalysisModes.includes(currentMode)) {
            runAnalysis(false);
        }
    }
    if (currentMode === 'montecarlo' && mcData.length > 0) {
        generateMontecarlo(true); // true = re-render only
    }

}



